#!/usr/bin/env bash
# Regenerates layer/src/shaders.inc from layer/shaders/*. Needs glslangValidator (glslang-tools).
# The output is checked in so building the layer needs no shader compiler; CI checks it's current.
set -euo pipefail
cd "$(dirname "$0")/.."
out=src/shaders.inc
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
{
  echo "// Generated by layer/scripts/gen-shaders.sh from layer/shaders. Do not edit."
  for f in fullscreen.vert crt.frag; do
    name=$(echo "$f" | tr '.' '_')
    glslangValidator -V --target-env vulkan1.0 -o "$tmp/$name.spv" "shaders/$f" >/dev/null
    echo "static const uint32_t k_${name}[] = {"
    od -An -v -t x4 -w16 "$tmp/$name.spv" | sed -E 's/ +([0-9a-f]{8})/0x\1, /g; s/^/   /; s/, $/,/'
    echo "};"
  done
} > "$out"
echo "wrote $out"
