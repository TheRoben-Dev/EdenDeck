using System.Globalization;

namespace EdenDeck.Backends.Mgba;

/// <summary>
/// The CRT effect for mGBA. mGBA draws with OpenGL, so Scanline's Vulkan CRT layer can't reach it;
/// instead Scanline writes its own mGBA shader (manifest.ini + GLSL, mGBA's shader format) and
/// passes it for that run with <c>-C shader=&lt;dir&gt;</c>. Same Subtle/Medium/Strong numbers as
/// the layer (layer/src/crt_settings.h), with scanlines on the game's own pixel rows. Nothing
/// moves (mGBA gives shaders no clock), like the layer with animations off.
/// </summary>
public static class MgbaCrt
{
    internal sealed record Look(float Strength, float Curve, float Chroma, float Vignette);

    private static Look? ForLevel(int level) => level switch
    {
        1 => new(0.7f, 0.02f, 0.6f, 0.15f),
        2 => new(1.0f, 0.035f, 1.0f, 0.25f),
        3 => new(1.4f, 0.05f, 1.5f, 0.28f),
        _ => null,
    };

    /// <summary>Writes the shader for this level and returns its folder, or null when the CRT effect is off.</summary>
    public static string? Write(string dataDir, int level)
    {
        if (ForLevel(level) is not { } look)
        {
            return null;
        }
        var dir = Path.Combine(dataDir, "mgba", "shaders", $"scanline-crt-{level}");
        Directory.CreateDirectory(dir);
        WriteIfChanged(Path.Combine(dir, "manifest.ini"), Manifest(level, look));
        WriteIfChanged(Path.Combine(dir, "crt.fs"), Fragment);
        return dir;
    }

    /// <summary>Where <see cref="Write"/> puts a level's shader (without writing it).</summary>
    public static string? DirFor(string dataDir, int level) =>
        ForLevel(level) == null ? null : Path.Combine(dataDir, "mgba", "shaders", $"scanline-crt-{level}");

    private static void WriteIfChanged(string path, string text)
    {
        if (!File.Exists(path) || File.ReadAllText(path) != text)
        {
            File.WriteAllText(path, text);
        }
    }

    private static string F(float v) => v.ToString("0.###", CultureInfo.InvariantCulture);

    internal static string Manifest(int level, Look look)
    {
        string Uniform(string id, float value) => $"""

            [pass.0.uniform.{id}]
            type=float
            default={F(value)}
            min=0.0
            max=2.0

            """;
        var label = level switch { 1 => "Subtle", 2 => "Medium", _ => "Strong" };
        return $"""
            [shader]
            name=Scanline CRT ({label})
            author=Scanline
            description=Scanline's CRT effect, written by the Scanline app.
            passes=1

            [pass.0]
            fragmentShader=crt.fs
            width=0
            height=0
            filter=1

            """
            + Uniform("strength", look.Strength) + Uniform("curve", look.Curve) + Uniform("chroma", look.Chroma) + Uniform("vignette", look.Vignette);
    }

    // GLSL that compiles under mGBA's GLES2, GL2 and GL3.2 headers (texture2D, varying, gl_FragColor).
    internal const string Fragment = """
        // Scanline CRT effect for mGBA. Generated by Scanline; changes are overwritten.
        uniform sampler2D tex;
        uniform vec2 texSize;
        varying vec2 texCoord;
        uniform float strength;
        uniform float curve;
        uniform float chroma;
        uniform float vignette;

        void main() {
            vec2 c = texCoord * 2.0 - 1.0;
            c *= 1.0 + curve * (c.yx * c.yx);
            vec2 uv = c * 0.5 + 0.5;
            float inside = step(0.0, uv.x) * step(uv.x, 1.0) * step(0.0, uv.y) * step(uv.y, 1.0);
            float ca = chroma * 0.25 / texSize.x;
            vec3 col = vec3(texture2D(tex, uv + vec2(ca, 0.0)).r, texture2D(tex, uv).g, texture2D(tex, uv - vec2(ca, 0.0)).b);
            float row = fract(uv.y * texSize.y);
            float lines = 1.0 - 0.18 * strength * smoothstep(0.55, 0.95, row);
            float vig = clamp(1.0 - vignette * dot(c * c, c * c) - vignette * 0.4 * dot(c, c), 0.0, 1.0);
            gl_FragColor = vec4(clamp(col * lines * vig * inside, 0.0, 1.0), 1.0);
        }
        """;
}
